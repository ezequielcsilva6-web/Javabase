package org.example;

public class Relacionais {
    public static void main(String[] args) {
        // Declaração de variavéis
        int a = 10;
        int b = 2;
        int maior;

        //Operadores aritiméticos
        if (a > b) {
            maior = a;
        } else {
            maior = b;
        }

        //Exibindo resultados
        System.out.println("O maior número é: " + maior);
    }
}
